"""Generate manuscript Markdown/LaTeX tables from audited comparison CSVs."""
import argparse
import csv
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
METRICS=('recall','precision','f1','auroc','false_positive_rate')


def load(folder,name):
    audit=json.loads((folder/'audit.json').read_text(encoding='utf-8'))
    path=folder/name
    if hashlib.sha256(path.read_bytes()).hexdigest()!=audit['exported_sha256'][name]:
        raise ValueError(f'Audited table changed: {path}')
    with path.open(encoding='utf-8',newline='') as stream:rows=list(csv.DictReader(stream))
    for row in rows:
        if int(row['n_seeds'])!=5:raise ValueError('Five seeds required')
    return rows


def one(rows,**keys):
    matches=[r for r in rows if all(r[k]==v for k,v in keys.items())]
    if len(matches)!=1:raise ValueError(f'Missing or duplicate result: {keys}')
    return matches[0]


def number(row,metric,signed=False):
    if int(row[metric+'_n_defined'])!=5:raise ValueError('Undefined seed metric')
    mean=float(row[metric+'_mean']);sd=float(row[metric+'_std'])
    return f'{mean:+.4f} ± {sd:.4f}' if signed else f'{mean:.3f} ± {sd:.3f}'


def tables():
    original=ROOT/'results/simulated_fall_p1_v2'
    fresh=ROOT/'results/fresh_trajectory_comparison'
    old=load(original,'summary.csv')
    current={e:load(fresh/f'epochs{e}','summary.csv') for e in (6,18)}
    delta=load(fresh/'epochs18','paired_P1_minus_B3_summary.csv')
    policy_headers=['Epochs','Scope','Policy','Recall','Precision','F1','AUROC','FPR']
    out=[]
    initial=[]
    for method in ('B1','B2','B3','P1'):
        r=one(old,method=method,scope='unseen',facility='__all__',geometry='__all__')
        initial.append(['6','unseen',method,*[number(r,m) for m in METRICS]])
    out.append(('Original unseen-geometry comparison',policy_headers,initial))
    rows=[]
    for scope in ('all','unseen'):
        for epoch in (6,18):
            for method in ('B1','B2','B3','P1'):
                r=one(current[epoch],method=method,scope=scope,facility='__all__',geometry='__all__')
                rows.append([str(epoch),scope,method,*[number(r,m) for m in METRICS]])
    out.append(('Same fresh trajectories at both training durations',policy_headers,rows))
    groups=[]
    for scope,facility in [('all','__all__'),('seen','__all__'),('unseen','__all__'),
                           ('seen','harsh'),('seen','standard'),('unseen','harsh'),('unseen','standard')]:
        r=one(delta,scope=scope,facility=facility,geometry='__all__')
        groups.append([scope,'pooled' if facility=='__all__' else facility,*[number(r,m,True) for m in ('recall','f1','false_positive_rate')]])
    out.append(('Fresh eighteen-epoch P1 minus B3: pooled and facility results',
                ['Scope','Facility','Recall difference','F1 difference','FPR difference'],groups))
    return out


def render():
    md=['# Manuscript result tables','',
        'Mean ± sample standard deviation over five model seeds sharing fixed trajectories; no significance claim.',
        'Calibration FPR budget 0.05. Original and fresh evaluation trajectories differ; compare durations only within the fresh dataset.',
        'Positive Recall/F1 differences and negative FPR differences favor P1. Facility tradeoffs must accompany pooled claims.','']
    tex=['% Generated by experiments/build_manuscript_results.py; do not edit numerical cells.',
         '% No extra LaTeX packages required. Tables may need venue-specific width/layout adjustments.',
         '% Mean +/- sample SD over five model seeds; shared trajectories, calibration FPR budget 0.05.']
    def escape(value):return value.replace('_',r'\_').replace('±',r'$\pm$')
    for title,headers,rows in tables():
        md += ['## '+title,'','| '+' | '.join(headers)+' |','|'+'|'.join('---' for _ in headers)+'|']
        md += ['| '+' | '.join(r)+' |' for r in rows]
        md.append('')
        tex += [r'\begin{table*}[t]',r'\centering',r'\scriptsize',r'\caption{'+title+'. Mean and sample standard deviation across five model seeds.}',
                r'\begin{tabular}{'+'l'*len(headers)+'}',r'\hline',' & '.join(headers)+r' \\',r'\hline']
        tex += [' & '.join(escape(v) for v in r)+r' \\' for r in rows]
        tex += [r'\hline',r'\end{tabular}',r'\end{table*}','']
    return '\n'.join(md).rstrip()+'\n','\n'.join(tex).rstrip()+'\n'


def check_prose(text):
    fresh=ROOT/'results/fresh_trajectory_comparison'
    six=load(fresh/'epochs6','summary.csv');eighteen=load(fresh/'epochs18','summary.csv')
    deltas=load(fresh/'epochs18','paired_P1_minus_B3_summary.csv')
    def row(table,method):return one(table,method=method,scope='unseen',facility='__all__',geometry='__all__')
    b2six=row(six,'B2');b2eighteen=row(eighteen,'B2');p1=row(eighteen,'P1');b3=row(eighteen,'B3')
    d=one(deltas,scope='unseen',facility='__all__',geometry='__all__')
    def value(r,m):return f'{float(r[m+"_mean"]):.4f}'
    checks=[f'from {value(b2six,"recall")} at six epochs to {value(b2eighteen,"recall")} at eighteen epochs',
            f'F1 from {value(b2six,"f1")} to {value(b2eighteen,"f1")}',
            f'AUROC from {value(b2six,"auroc")} to {value(b2eighteen,"auroc")}',
            f'recall {value(p1,"recall")} versus {value(b3,"recall")}',
            f'F1 {value(p1,"f1")} versus {value(b3,"f1")}',
            f'FPR {value(p1,"false_positive_rate")} versus {value(b3,"false_positive_rate")}',
            f'approximately {number(d,"recall",True)} in recall, {number(d,"f1",True)} in F1, and {number(d,"false_positive_rate",True)} in FPR']
    for facility in ('harsh','standard'):
        r=one(deltas,scope='unseen',facility=facility,geometry='__all__')
        checks.append(f'{float(r["recall_mean"]):+.4f} in recall and {float(r["false_positive_rate_mean"]):+.4f} in FPR')
    for phrase in checks:
        if phrase not in text:raise ValueError(f'Manuscript evidence missing or changed: {phrase}')
    return len(checks)


def main(check=False):
    for filename,content in zip(('RESULTS_TABLES.md','results_tables.tex'),render()):
        path=ROOT/'paper'/filename
        if check:
            if not path.exists() or path.read_text(encoding='utf-8')!=content:
                raise ValueError(f'Generated manuscript table is stale: {filename}')
        else:path.write_text(content,encoding='utf-8')
    count=check_prose((ROOT/'paper/DRAFT.md').read_text(encoding='utf-8'))
    print(f'Verified audited tables and {count} key numerical statements' if check else 'Generated Markdown and LaTeX manuscript tables')


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true')
    main(p.parse_args().check)
